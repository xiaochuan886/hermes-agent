class TestManifestChecksum:
    def test_manifest_checksum_mismatch_raises_without_leaking(self):
        manifest = _base_manifest()
        payload = _base_payload(manifestSha256="0" * 64, manifest=manifest)
        with pytest.raises(ChecksumMismatchError) as exc_info:
            parse_runtime_assignment(payload)
        message = str(exc_info.value)
        assert MANIFEST_CANARY not in message
        assert sha256_hex(canonical_json_bytes(manifest)) not in message

    def test_manifest_tamper_after_correct_sha_detected(self):
        manifest = _base_manifest()
        good_sha = sha256_hex(canonical_json_bytes(manifest))
        tampered = {**manifest, "note": "tampered"}
        payload = _base_payload(manifest=tampered, manifestSha256=good_sha)
        with pytest.raises(ChecksumMismatchError):
            parse_runtime_assignment(payload)

    def test_manifest_and_policy_use_different_contracts(self):
        """The manifest digest (canonical JSON) must differ from any naive
        canonical-JSON digest of the policy — proving the two contracts are
        not conflated.  The policy golden SHA is NOT a canonical-JSON digest."""
        vector = GOLDEN_VECTORS[0]
        policy = {k: v for k, v in _golden_policy(vector).items() if k != "note"}
        canonical_policy_sha = sha256_hex(canonical_json_bytes(policy))
        assert canonical_policy_sha != vector["policySha256"]


