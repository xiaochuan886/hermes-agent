def _golden_policy(vector: dict) -> dict:
    """Build a policy dict matching a golden vector (extra fields allowed)."""
    return {
        "mode": vector["mode"],
        "allowedModels": list(vector["allowedModels"]),
        "defaultModel": vector["defaultModel"],
        "fallbackModels": list(vector["fallbackModels"]),
        "localProviderAllowed": vector["localProviderAllowed"],
        "policyVersion": vector["policyVersion"],
        "policySha256": vector["policySha256"],
        "note": POLICY_CANARY,
    }


