class TestPolicyChecksumGoldenVectors:
    """The parser must accept each Java-generated golden policy and surface the
    exact fixed SHA.  These SHAs come from SkillHub's PolicyChecksum.java, not
    from the Python framing function under test."""

    @pytest.mark.parametrize("vector", GOLDEN_VECTORS, ids=[v["id"] for v in GOLDEN_VECTORS])
    def test_golden_policy_parses_with_fixed_sha(self, vector):
        payload = _base_payload(effectiveModelPolicy=_golden_policy(vector))
        assignment = parse_runtime_assignment(payload)
        assert assignment.effective_model_policy["policySha256"] == vector["policySha256"]
        assert assignment.effective_model_policy["policyVersion"] == vector["policyVersion"]

    @pytest.mark.parametrize("vector", GOLDEN_VECTORS, ids=[v["id"] for v in GOLDEN_VECTORS])
    def test_golden_policy_version_is_sha_prefix(self, vector):
        assert vector["policyVersion"] == "sha256:" + vector["policySha256"][:12]

    def test_non_ascii_vector_uses_utf8_byte_length(self):
        """The non-ASCII golden vector proves the V framing counts UTF-8 bytes,
        not code points (中文模型 = 12 bytes, café = 5 bytes)."""
        vector = next(v for v in GOLDEN_VECTORS if v["id"] == "non_ascii_utf8_byte_length")
        assert "V23:enterprise/中文模型" in vector["framed"]
        assert "V16:enterprise/café" in vector["framed"]
        payload = _base_payload(effectiveModelPolicy=_golden_policy(vector))
        parse_runtime_assignment(payload)  # must not raise

    def test_java_test_cross_check_matches_skillhub_test_literal(self):
        """Cross-validates the harness against the literal SHA asserted by
        SkillHub's own EffectiveModelPolicyResolverTest."""
        vector = next(v for v in GOLDEN_VECTORS if v["id"] == "java_test_cross_check")
        assert vector["policySha256"] == (
            "c691e382c4f337ac5e93d492804200a4a4e1650cab6f11685556abeaef30901c"
        )


class TestPolicyChecksumFailures:
    def test_policy_sha_mismatch_raises_without_leaking(self):
        vector = GOLDEN_VECTORS[0]
        policy = _golden_policy(vector)
        policy["policySha256"] = "1" * 64  # valid format, wrong value
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(ChecksumMismatchError) as exc_info:
            parse_runtime_assignment(payload)
        assert POLICY_CANARY not in str(exc_info.value)

    def test_policy_version_mismatch_raises(self):
        vector = GOLDEN_VECTORS[0]
        policy = _golden_policy(vector)
        # policySha256 is correct, but policyVersion does not match its prefix.
        policy["policyVersion"] = "sha256:deadbeefdead"
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(ChecksumMismatchError) as exc_info:
            parse_runtime_assignment(payload)
        assert "policyversion" in str(exc_info.value).lower()

    def test_policy_version_not_sha_prefixed_rejected(self):
        vector = GOLDEN_VECTORS[0]
        policy = _golden_policy(vector)
        policy["policyVersion"] = "v1"  # legacy free-form version, no longer valid
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(ChecksumMismatchError):
            parse_runtime_assignment(payload)

    def test_missing_policy_sha256_rejected(self):
        policy = _golden_policy(GOLDEN_VECTORS[0])
        del policy["policySha256"]
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(MissingRequiredFieldError) as exc_info:
            parse_runtime_assignment(payload)
        assert POLICY_CANARY not in str(exc_info.value)

    def test_missing_policy_version_rejected(self):
        policy = _golden_policy(GOLDEN_VECTORS[0])
        del policy["policyVersion"]
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(MissingRequiredFieldError):
            parse_runtime_assignment(payload)

    def test_policy_sha_bad_format_rejected(self):
        policy = _golden_policy(GOLDEN_VECTORS[0])
        policy["policySha256"] = "not-hex"
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises((FieldTypeError, ChecksumMismatchError)) as exc_info:
            parse_runtime_assignment(payload)
        assert POLICY_CANARY not in str(exc_info.value)

    def test_allowed_models_order_changes_sha(self):
        """Reordering allowedModels must change the framed digest (list order
        is significant), so the original SHA no longer verifies."""
        vector = GOLDEN_VECTORS[1]  # has 2 allowed models
        policy = _golden_policy(vector)
        policy["allowedModels"] = list(reversed(policy["allowedModels"]))
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(ChecksumMismatchError):
            parse_runtime_assignment(payload)

    def test_fallback_models_order_changes_sha(self):
        vector = next(v for v in GOLDEN_VECTORS if v["id"] == "local_true")
        # Build a vector with 2 fallbacks by reusing allowed models as fallbacks.
        policy = _golden_policy(GOLDEN_VECTORS[1])
        policy["fallbackModels"] = ["enterprise/gpt-5"]
        # original vector[1] already has fallback [enterprise/gpt-5]; reverse is same.
        # Instead, append an extra fallback that is also allowed to force order sensitivity.
        policy["allowedModels"] = ["enterprise/deepseek-chat", "enterprise/gpt-5", "enterprise/extra"]
        policy["defaultModel"] = "enterprise/deepseek-chat"
        policy["fallbackModels"] = ["enterprise/gpt-5", "enterprise/extra"]
        # With this ordering the SHA will not match vector[1]'s golden SHA.
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(ChecksumMismatchError):
            parse_runtime_assignment(payload)

    def test_local_provider_bool_string_matters(self):
        """Flipping localProviderAllowed changes 'false'→'true' and the digest."""
        vector = GOLDEN_VECTORS[0]  # local=false
        policy = _golden_policy(vector)
        policy["localProviderAllowed"] = True
        payload = _base_payload(effectiveModelPolicy=policy)
        with pytest.raises(ChecksumMismatchError):
            parse_runtime_assignment(payload)

    def test_policy_field_type_errors(self):
        for field, bad in [
            ("mode", 123),
            ("allowedModels", "not-a-list"),
            ("allowedModels", [1, 2]),
            ("defaultModel", None),
            ("fallbackModels", "x"),
            ("localProviderAllowed", "true"),
        ]:
            policy = _golden_policy(GOLDEN_VECTORS[0])
            policy[field] = bad
            payload = _base_payload(effectiveModelPolicy=policy)
            with pytest.raises((FieldTypeError, MissingRequiredFieldError, ChecksumMismatchError)):
                parse_runtime_assignment(payload)


